
class Example01 {

	static void sayHello(){
		System.out.println("Hello Hello Hello");
	}
	static void sayBye(){
		System.out.println("Bye Bye Bye");
	}

	public static void main(String[] args) {
		

			sayHello(); // METHOD CALL
			sayBye();
			sayHello(); // METHOD CALL
			sayBye();
			sayHello(); // METHOD CALL
			sayHello(); // METHOD CALL
			sayHello(); // METHOD CALL
			sayBye();
	}
	
}